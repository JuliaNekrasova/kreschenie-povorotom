#!/usr/bin/env python3
"""Проверка регистра изложения перед сборкой материала.

    python3 _tools/proverit_stil.py                 # все материалы проекта
    python3 _tools/proverit_stil.py <имя_папки>     # один материал

Скрипт ищет конструкции, запрещённые стилевым стандартом проекта
(AGENTS.md, раздел «СТИЛЬ»): разговорную лексику, оценочные обороты,
заголовки-реплики и вопросительные заголовки, обращения к читателю,
метафоры вместо терминов.

Блок «Слово бригаде» из проверки исключается: это цитата из дневника,
и она не редактируется в академический вид.

Код возврата 1 при наличии находок, 0 при их отсутствии.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent.parent

# (регулярное выражение, что именно нарушено, чем заменять)
PRAVILA: list[tuple[str, str, str]] = [
    # --- разговорная лексика и метафоры вместо терминов
    # «устройство аппарата» правомерно; «устройство боли», «устройство синдрома» — нет
    (r'\bустройств[оаеу]\s+(?:фантомной\s+)?(бол\w+|синдром\w+|процесс\w+|заболеван\w+|механизм\w+|недостаточност\w+)',
     'разговорное «устройство» применительно к патологии',
     'патофизиология, механизмы формирования'),
    # «аппарат работает» правомерно; «препарат работает» — нет
    (r'(?<!аппарат )(?<!прибор )(?<!клапан )(?<!датчик )(?<!турбина )(?<!насос )'
     r'(препарат|морфин|габапентин|кетамин|метод|терапия|блокада|схема)\w*\s+(?:действительно\s+)?работа(ет|ют)',
     'разговорное «работает» о препарате или методе',
     'эффективен, обладает подтверждённой эффективностью'),
    (r'\b(снимает|снять) (боль|приступ|симптом)', 'разговорное «снимает боль»',
     'купирует, уменьшает интенсивность'),
    (r'\bтруб[аыуе]\b', 'метафора «труба»', 'термин, обозначающий конкретную структуру'),
    (r'\bкарт[аоуы] поиска\b', 'метафора «карта поиска»', 'перечень направлений поиска'),
    (r'\bпроблем[аыуе]\b', 'разговорное «проблема»', 'нарушение, расстройство, вопрос, задача'),
    (r'\bпочинить|сломал(ся|ась|ось)\b', 'разговорная метафора поломки', 'нарушение функции, отказ'),

    # --- оценочность и публицистика
    (r'\bглавное\b', 'оценочное «главное»', 'имеет наибольшее значение, определяющим является'),
    (r'\bсамое важное\b', 'оценочное «самое важное»', 'определяющее значение имеет'),
    (r'\bпринципиальн(ое|ая) в', 'публицистический оборот «принципиальное в»', 'значение состоит в'),
    (r'\bпросто\b', 'разговорное «просто»', 'убрать или заменить на количественную характеристику'),
    (r'\bдействительно\b', 'усилительное «действительно»', 'убрать'),
    (r'\bконечно\b', 'вводное «конечно»', 'убрать'),
    (r'\bужасн|страшн|катастрофичес', 'эмоциональная оценка', 'нейтральная формулировка'),
    (r'\bморально\b', 'оценочное «морально»', 'деонтологический'),

    # --- обращения к читателю, дидактика, повелительное наклонение
    (r'\b(нужно|надо|следует) (помнить|знать|понимать)\b', 'дидактическая конструкция',
     'утверждение без обращения к читателю'),
    (r'\bзапомни|учти|обрати внимание\b', 'обращение к читателю', 'убрать'),
    (r'\bвы (видите|понимаете|знаете)\b', 'обращение к читателю', 'убрать'),

    # --- неопределённость там, где нужны числа
    (r'\bпримерно (в|на) \d', 'приблизительность при наличии числа', 'точное значение либо диапазон'),
    (r'\b(наверное|по-видимому, что|вроде бы)\b', 'неопределённость в утверждении',
     'указание степени достоверности: показано, предполагается, не установлено'),
]

# заголовки: вопросительные и в форме реплики
PRAVILA_ZAGOLOVKOV: list[tuple[str, str, str]] = [
    (r'^#{1,3} .*\?\s*$', 'вопросительный заголовок', 'назывной терминологический заголовок'),
    (r'^#{1,3} .*: (что|чем|как|почему|где|зачем|когда)\b', 'заголовок-реплика',
     'назывной терминологический заголовок'),
    (r'^#{1,3} (Итог|Практическое значение|Ключевые отличия|Типичный портрет|Клинические подсказки)\b',
     'публицистический заголовок', 'терминологический заголовок'),
    (r'^\*\*(Что|Почему|Как|Чем|Зачем|Где) ', 'полужирный ввод в вопросительной форме',
     'назывной ввод: «Обоснование…», «Ограничения…», «Показание…»'),
]

# эмодзи и восклицания
PRAVILA_ZNAKOV: list[tuple[str, str, str]] = [
    (r'[\U0001F300-\U0001FAFF\u2600-\u27BF]', 'эмодзи', 'убрать'),
    (r'!(?!\=)', 'восклицательный знак', 'убрать, кроме предупреждения о дозе'),
]


def bez_citaty(tekst: str) -> str:
    """Убирает из проверки то, что стандарту не подчиняется.

    Это блок «Слово бригаде» — цитата из дневника, и дословные цитаты
    документов: в них восклицательные знаки и формулировки первоисточника
    сохраняются без изменений.
    """
    m = re.search(r'^##+ Слово бригаде\s*$', tekst, re.M)
    if m:
        sled = re.search(r'^#{1,3} ', tekst[m.end():], re.M)
        konec = m.end() + (sled.start() if sled else len(tekst) - m.end())
        tekst = tekst[:m.start()] + tekst[konec:]

    # дословные цитаты и предупреждения первоисточника заменяются пробелами
    # той же длины, чтобы номера строк не сдвигались
    def zateret(m: re.Match) -> str:
        return re.sub(r'[^\n]', ' ', m.group(0))

    tekst = re.sub(r'«[^»\n]{0,400}»', zateret, tekst)
    tekst = re.sub(r'^.*(Внимание|Предупреждение|Запрещено|Противопоказан)[^\n]*$', zateret, tekst, flags=re.M)
    return tekst


def nomer_stroki(tekst: str, poziciya: int) -> int:
    return tekst.count('\n', 0, poziciya) + 1


def proverit(put: Path) -> list[str]:
    ishodnyy = put.read_text(encoding='utf-8')
    tekst = bez_citaty(ishodnyy)
    nahodki: list[str] = []

    for shablon, chto, chem in PRAVILA + PRAVILA_ZNAKOV:
        for m in re.finditer(shablon, tekst, re.I | re.M):
            stroka = nomer_stroki(tekst, m.start())
            kontekst = re.sub(r'\s+', ' ', tekst[max(0, m.start() - 45):m.end() + 45]).strip()
            nahodki.append(f'  стр. {stroka}: {chto} — «{m.group(0)}» → {chem}\n      …{kontekst}…')

    for shablon, chto, chem in PRAVILA_ZAGOLOVKOV:
        for m in re.finditer(shablon, tekst, re.M):
            stroka = nomer_stroki(tekst, m.start())
            nahodki.append(f'  стр. {stroka}: {chto} → {chem}\n      {m.group(0).strip()[:110]}')

    return nahodki


def vse_materialy() -> list[Path]:
    return sorted(KOREN.glob('*/*/razbor.md'))


def main() -> int:
    # без этого вывод при перенаправлении в файл падает на Windows: там cp1251
    try:
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    except AttributeError:
        pass

    if len(sys.argv) > 1:
        puti = [p for p in vse_materialy() if p.parent.name == sys.argv[1]]
        if not puti:
            print(f'материал «{sys.argv[1]}» не найден')
            return 2
    else:
        puti = vse_materialy()

    vsego = 0
    for put in puti:
        nahodki = proverit(put)
        if nahodki:
            vsego += len(nahodki)
            print(f'\n{put.relative_to(KOREN)} — находок: {len(nahodki)}')
            for n in nahodki:
                print(n)

    print(f'\nПроверено материалов: {len(puti)}. Находок: {vsego}.')
    if vsego:
        print('Регистр изложения не соответствует стандарту проекта (AGENTS.md, раздел «СТИЛЬ»).')
    return 1 if vsego else 0


if __name__ == '__main__':
    sys.exit(main())
